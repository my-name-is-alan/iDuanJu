    private val t2sMap: Map<Char, Char> by lazy {
        HashMap<Char, Char>(PAIRS.length).apply {
            var i = 0
            while (i + 1 < PAIRS.length) {
                val t = PAIRS[i]; val s = PAIRS[i + 1]
                if (t != s) putIfAbsent(t, s)
                i += 2
            }
        }
    }

    private val s2tMap: Map<Char, Char> by lazy {
        HashMap<Char, Char>(PAIRS.length).apply {
            var i = 0
            while (i + 1 < PAIRS.length) {
                val t = PAIRS[i]; val s = PAIRS[i + 1]
                if (t != s) putIfAbsent(s, t)
                i += 2
            }
        }
    }

    fun t2s(s: String): String {
        if (s.isEmpty()) return s
        val sb = StringBuilder(s.length)
        for (c in s) sb.append(t2sMap[c] ?: c)
        return sb.toString()
    }

    fun s2t(s: String): String {
        if (s.isEmpty()) return s
        val sb = StringBuilder(s.length)
        for (c in s) sb.append(s2tMap[c] ?: c)
        return sb.toString()
    }

    private val chapterPattern = Regex("(第\\s*)([零〇一二两三四五六七八九十百千万亿]+)(\\s*[章节回卷集部篇话])")

    fun toNumChapter(title: String?): String? {
        if (title == null) return null
        return chapterPattern.replace(title) { m ->
            val n = chineseToLong(m.groupValues[2])
            if (n != null) "${m.groupValues[1]}$n${m.groupValues[3]}" else m.value
        }
    }

    internal fun chineseToLong(raw: String): Long? {
        if (raw.isEmpty()) return null
        val digits = mapOf('零' to 0L, '〇' to 0L, '一' to 1L, '二' to 2L, '两' to 2L, '三' to 3L, '四' to 4L, '五' to 5L, '六' to 6L, '七' to 7L, '八' to 8L, '九' to 9L)
        val units = mapOf('十' to 10L, '百' to 100L, '千' to 1000L)
        if (raw.all { it in digits }) {
            return raw.fold(0L) { acc, c -> acc * 10L + digits[c]!! }
        }
        var total = 0L
        var section = 0L
        var number = 0L
        for (c in raw) {
            when {
                c in digits -> number = digits[c]!!
                c in units -> {
                    val u = units[c]!!
                    section += (if (number == 0L && u == 10L) 1L else number) * u
                    number = 0L
                }
                c == '万' -> { total += (section + number) * 10_000L; section = 0L; number = 0L }
                c == '亿' -> { total += (section + number) * 100_000_000L; section = 0L; number = 0L }
                else -> return null
            }
        }
        return total + section + number
    }
